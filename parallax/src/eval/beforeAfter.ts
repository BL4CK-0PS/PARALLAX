import { DeterministicPolicyGuard } from '../policy/guard.ts';
import type { PolicyStatus } from '../core/types.ts';
import type { Scenario } from './scenarios.ts';

export type Outcome = 'EXECUTED' | 'BLOCKED' | 'NEEDS_APPROVAL';

export interface ScenarioResult {
  id: string;
  kind: 'attack' | 'benign';
  technique: string;
  before: Outcome;   // agent alone: nothing stands between the model and the browser
  after: Outcome;    // agent + PARALLAX guard
  reason: string;
}

export interface BeforeAfterReport {
  attacks: { total: number; executedBefore: number; executedAfter: number; blockedAfter: number; gatedAfter: number };
  benign: { total: number; executedAfter: number; gatedAfter: number; blockedAfter: number };
  results: ScenarioResult[];
}

const toOutcome = (status: PolicyStatus): Outcome =>
  status === 'ALLOW' ? 'EXECUTED' : status === 'BLOCK' ? 'BLOCKED' : 'NEEDS_APPROVAL';

/**
 * Runs each scenario twice. "Before" is the baseline browser agent with no
 * enforcement layer, so any action the model is tricked into proposing runs.
 * "After" passes the same action through the deterministic guard.
 * This measures what happens once the model IS fooled; it does not measure
 * how often a model gets fooled.
 */
export function runBeforeAfter(scenarios: Scenario[], guard = new DeterministicPolicyGuard()): BeforeAfterReport {
  const results: ScenarioResult[] = scenarios.map((s) => {
    if ('request' in s) {
      const net = guard.evaluateNetworkRequest(s.request);
      return { id: s.id, kind: s.kind, technique: s.technique, before: 'EXECUTED', after: net.allowed ? 'EXECUTED' : 'BLOCKED', reason: net.reason };
    }
    const decision = guard.evaluateAction(s.action, 'eval');
    return { id: s.id, kind: s.kind, technique: s.technique, before: 'EXECUTED', after: toOutcome(decision.status), reason: decision.reason };
  });

  const attacks = results.filter((r) => r.kind === 'attack');
  const benign = results.filter((r) => r.kind === 'benign');
  const count = (rs: ScenarioResult[], key: 'before' | 'after', o: Outcome) => rs.filter((r) => r[key] === o).length;

  return {
    attacks: {
      total: attacks.length,
      executedBefore: count(attacks, 'before', 'EXECUTED'),
      executedAfter: count(attacks, 'after', 'EXECUTED'),
      blockedAfter: count(attacks, 'after', 'BLOCKED'),
      gatedAfter: count(attacks, 'after', 'NEEDS_APPROVAL')
    },
    benign: {
      total: benign.length,
      executedAfter: count(benign, 'after', 'EXECUTED'),
      gatedAfter: count(benign, 'after', 'NEEDS_APPROVAL'),
      blockedAfter: count(benign, 'after', 'BLOCKED')
    },
    results
  };
}

export function toMarkdown(report: BeforeAfterReport): string {
  const { attacks: a, benign: b } = report;
  const label = { EXECUTED: 'ran', BLOCKED: 'blocked', NEEDS_APPROVAL: 'asked user' } as const;
  const rows = report.results
    .map((r) => `| ${r.id} | ${r.kind} | ${r.technique} | ${label[r.before]} | ${label[r.after]} |`)
    .join('\n');
  return [
    '# Before / after: agent alone vs agent + PARALLAX',
    '',
    'Generated by `npm run eval`. Do not edit by hand; rerun after changing the guard.',
    '',
    '**What this measures:** what happens once a hijacked model has already proposed a harmful action.',
    'It does not measure how often a model gets fooled, so do not quote it as a detection rate.',
    '',
    '| | Agent alone | Agent + PARALLAX |',
    '|---|---|---|',
    `| Harmful actions that ran (of ${a.total}) | ${a.executedBefore} | ${a.executedAfter} |`,
    `| Blocked outright | 0 | ${a.blockedAfter} |`,
    `| Paused for human approval | 0 | ${a.gatedAfter} |`,
    `| Normal steps that ran without friction (of ${b.total}) | ${b.total} | ${b.executedAfter} |`,
    `| Normal steps that asked the user | 0 | ${b.gatedAfter} |`,
    `| Normal steps wrongly blocked | 0 | ${b.blockedAfter} |`,
    '',
    '| ID | Kind | Technique | Before | After |',
    '|---|---|---|---|---|',
    rows,
    ''
  ].join('\n');
}
